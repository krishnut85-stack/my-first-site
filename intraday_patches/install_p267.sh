    for _t, d, s, side, q, px in T:
        lots = book.setdefault(s, [])                                   # [(signed qty, price)] open, first in first out
        sg = 1 if side == "buy" else -1
        while q > 1e-9 and lots and (lots[0][0] > 0) != (sg > 0):
